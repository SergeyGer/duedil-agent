#!/usr/bin/env python3
"""Generate ``docs/wiki/Reference.md`` from the code, so the reference cannot drift.

Hand-written reference tables rot: a flag is renamed, a variable disappears, and the page
still promises it. Everything on this page is therefore derived from the repository:

* environment variables  -> ``env.example``
* CLI options            -> the ``add_argument`` calls in ``app/cli.py``
* helper scripts         -> the header comment of each script in ``scripts/``
* wiki pages             -> the ``# heading`` of every ``docs/wiki/*.md``

Run it through ``make wiki-reference``. ``scripts/validate_docs.py`` regenerates the page
in memory and fails the Docs check when the committed copy is stale.

Standard library only: the Docs CI job runs before installing the application.
"""

from __future__ import annotations

import argparse
import ast
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
WIKI = ROOT / "docs" / "wiki"
OUTPUT = WIKI / "Reference.md"

#: Wiki metadata required by scripts/validate_docs.py on every page.
REVIEWED = "*Last reviewed: 2026-10-23 · Owner: [@SergeyGer](https://github.com/SergeyGer)*"

GENERATED_NOTICE = (
    "<!-- Generated by scripts/make_wiki_reference.py — do not edit by hand.\n"
    "     Run `make wiki-reference` after changing env.example, app/cli.py or scripts/. -->"
)


_SECTION_RE = re.compile(r"^#\s*[-=]{2,}\s*(.+?)\s*[-=]{2,}\s*$")


def _env_vars() -> list[tuple[str, str, str, str]]:
    """``(name, section, default, description)`` parsed from env.example.

    Comment blocks become the description of the next variable; ``--- Section ---``
    comments are section markers instead, which keeps the table readable.
    """

    path = ROOT / "env.example"
    if not path.is_file():
        return []
    rows: list[tuple[str, str, str, str]] = []
    pending: list[str] = []
    section = "General"
    for line in path.read_text(encoding="utf-8").splitlines():
        stripped = line.strip()
        if stripped.startswith("#"):
            text = stripped.lstrip("#").strip()
            if not text:
                continue
            section_match = _SECTION_RE.match(stripped)
            if section_match:
                section = section_match.group(1).strip()
                pending = []
                continue
            if text.startswith(("LANGCHAIN_", "LANGSMITH_WORKSPACE_ID=")):
                continue  # the alias block has its own paragraph above it
            pending.append(text)
            continue
        match = re.match(r"^([A-Z0-9_]+)\s*=\s*(.*)$", stripped)
        if not match:
            continue
        name, default = match.group(1), match.group(2).strip() or "—"
        description = " ".join(pending).strip() or "—"
        # Keep the table narrow: the first sentence is enough.
        description = re.split(r"(?<=\.)\s", description)[0]
        rows.append((name, section, default, description))
        pending = []
    return rows


def _cli_options() -> list[tuple[str, str]]:
    """``(flags, help)`` for every ``add_argument`` call in app/cli.py, in source order.

    Parsed from the AST rather than imported: importing the CLI pulls in LangChain, and the
    Docs CI job must run before the application dependencies are installed.
    """

    path = ROOT / "app" / "cli.py"
    if not path.is_file():
        return []
    tree = ast.parse(path.read_text(encoding="utf-8"))
    options: list[tuple[str, str]] = []
    for node in ast.walk(tree):
        if not isinstance(node, ast.Call) or not isinstance(node.func, ast.Attribute):
            continue
        if node.func.attr != "add_argument":
            continue
        names = [
            arg.value
            for arg in node.args
            if isinstance(arg, ast.Constant) and isinstance(arg.value, str)
        ]
        if not names:
            continue
        help_text = "—"
        for keyword in node.keywords:
            if keyword.arg == "help" and isinstance(keyword.value, ast.Constant):
                help_text = " ".join(str(keyword.value.value).split())
        options.append((", ".join(f"`{name}`" for name in names), help_text))
    return options


_PURPOSE = re.compile(r"^#\s*(?!\!)(.+)$")


def _scripts() -> list[tuple[str, str]]:
    """``(file, purpose)`` for every executable script, from its header comment."""

    scripts_dir = ROOT / "scripts"
    rows: list[tuple[str, str]] = []
    for path in sorted(scripts_dir.iterdir()):
        if not path.is_file() or path.suffix not in {".sh", ".ps1", ".py"}:
            continue
        if path.name == "make_wiki_reference.py":
            continue
        purpose = "—"
        if path.suffix == ".py":
            docstring = ast.get_docstring(ast.parse(path.read_text(encoding="utf-8"))) or ""
            if docstring.strip():
                purpose = docstring.strip().splitlines()[0]
        else:
            for line in path.read_text(encoding="utf-8").splitlines()[:40]:
                match = _PURPOSE.match(line.strip())
                if match:
                    text = match.group(1).strip()
                    # Skip echo/parameter blocks and the PowerShell synopsis markers.
                    if text and not re.match(r"^(=|RESULT|\.|<#)", text):
                        purpose = text
                        break
        rows.append((f"`scripts/{path.name}`", purpose))
    return rows


def _wiki_pages() -> list[tuple[str, str]]:
    """``(page, title)`` for every wiki page except the generated one and the sidebar."""

    rows: list[tuple[str, str]] = []
    for path in sorted(WIKI.glob("*.md")):
        if path.name in {"_Sidebar.md", OUTPUT.name}:
            continue
        title = path.stem.replace("-", " ")
        for line in path.read_text(encoding="utf-8").splitlines():
            if line.startswith("# "):
                title = line[2:].strip()
                break
        rows.append((f"[{title}]({path.stem})", path.name))
    return rows


def _table(headers: list[str], rows: list[tuple[str, ...]]) -> list[str]:
    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join(["---"] * len(headers)) + "|"]
    for row in rows:
        cells = [str(cell).replace("|", "\\|") for cell in row]
        lines.append("| " + " | ".join(cells) + " |")
    return lines


def render() -> str:
    """Build the whole page as a deterministic string."""

    lines: list[str] = [
        GENERATED_NOTICE,
        "",
        "# Reference",
        "",
        "Generated from the code: environment variables, CLI options, helper scripts and the",
        "wiki index. Regenerate with `make wiki-reference`; the Docs check fails if this page",
        "is out of date.",
        "",
        "## Environment variables",
        "",
        *(
            _table(
                ["Variable", "Section", "Default in `env.example`", "What it controls"], _env_vars()
            )
        ),
        "",
        "The app runs without any of these: with no LLM key it falls back to the rule-based",
        "offline agents, and with no `LLAMA_CLOUD_API_KEY` the PDF parser degrades to `pypdf`.",
        "Commented-out entries in `env.example` are optional advanced switches.",
        "",
        "## CLI options",
        "",
        "`python -m app.cli <deck.pdf> [url] [options]`",
        "",
        *(_table(["Option", "Meaning"], _cli_options())),
        "",
        "## Helper scripts",
        "",
        *(_table(["Script", "Purpose"], _scripts())),
        "",
        "## Wiki pages",
        "",
        *(_table(["Page", "File"], _wiki_pages())),
        "",
        REVIEWED,
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate docs/wiki/Reference.md from the code.")
    parser.add_argument("--out", default=str(OUTPUT))
    parser.add_argument(
        "--check",
        action="store_true",
        help="do not write; exit 1 when the committed page differs from the generated one",
    )
    args = parser.parse_args(argv)

    path = Path(args.out)
    rendered = render()
    if args.check:
        current = path.read_text(encoding="utf-8") if path.is_file() else ""
        if current != rendered:
            print(f"{path} is stale — run `make wiki-reference`", file=sys.stderr)
            return 1
        print(f"{path} is up to date")
        return 0

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(rendered, encoding="utf-8", newline="\n")
    print(f"Wrote {path} ({len(rendered.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

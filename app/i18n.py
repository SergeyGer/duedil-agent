def translate(language: str, key: str, **kwargs: object) -> str:
    """Return ``key`` in ``language`` (falling back to English), formatted with ``kwargs``."""

    table = TRANSLATIONS.get(language) or TRANSLATIONS[DEFAULT_LANGUAGE]
    template = table.get(key) or TRANSLATIONS[DEFAULT_LANGUAGE].get(key, key)
    try:
        return template.format(**kwargs)
    except (KeyError, IndexError):
        return template


